import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Whole templates are shared by the server renderer and browser. Run after editing FindingText.java.
const root = fileURLToPath(new URL("../../", import.meta.url));
const source = readFileSync(`${root}backend/src/main/java/com/dealanalyzer/report/FindingText.java`, "utf8");
const entries = [...source.matchAll(/add\(("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*")\);/g)]
  .map(match => match.slice(1).map(value => JSON.parse(value)));
if (!entries.length) throw new Error("No finding templates read");
const addOns = JSON.parse(readFileSync(`${root}backend/src/main/resources/fees/dealer-add-ons.v1.json`, "utf8"));
const spanishAddOns = JSON.parse(readFileSync(`${root}backend/src/main/resources/i18n/dealer-add-ons.es.json`, "utf8"));
for (const entry of addOns.entries) {
  const translated = spanishAddOns[entry.id];
  if (translated?.length !== 3) throw new Error(`Missing Spanish add-on: ${entry.id}`);
  for (const [index, field] of ["name", "what", "question"].entries())
    entries.push([`ADDON_${entry.id.replaceAll("-", "_").toUpperCase()}_${field.toUpperCase()}`, entry[field], translated[index]]);
}
const stateFees = JSON.parse(readFileSync(`${root}backend/src/main/resources/fees/government-fees.v1.json`, "utf8"));
const spanishFees = JSON.parse(readFileSync(`${root}backend/src/main/resources/i18n/government-fees.es.json`, "utf8"));
for (const state of stateFees.states) for (const fee of state.fees) {
  const translated = spanishFees[fee.id];
  if (translated?.length !== 2) throw new Error(`Missing Spanish state fee: ${fee.id}`);
  entries.push([`STATE_${fee.id}_NAME`, fee.name, translated[0]], [`STATE_${fee.id}_PURPOSE`, fee.purpose, translated[1]]);
}
for (const [language, index] of [["en", 1], ["es", 2]]) {
  const values = Object.fromEntries(entries.map(entry => [entry[0], entry[index]]));
  const out = `// Generated by scripts/generate-finding-catalogues.mjs from FindingText.java.\nexport const templates = ${JSON.stringify(values, null, 2)} as const;\n`;
  writeFileSync(`${root}frontend/src/i18n/${language}/findingTemplates.ts`, out);
}
